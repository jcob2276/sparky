import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
const user = '11111111-1111-4111-8111-111111111111';
const id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
try {
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.user',true),'')::uuid$$;
    create table finance_holdings(id uuid primary key,user_id uuid,ticker text,name text,quantity numeric,avg_cost_pln numeric,avg_cost_original numeric,avg_cost_currency text default 'PLN',updated_at timestamptz);
    create table finance_accounts(id uuid primary key,user_id uuid,balance numeric,bank_account_id uuid,account_type text);
    alter table finance_holdings enable row level security;
    create policy owner on finance_holdings for all to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
    grant select,insert,update,delete on finance_holdings to authenticated;
    grant select,update on finance_accounts to authenticated;
    grant usage on schema auth to authenticated;
    grant execute on function auth.uid() to authenticated;`);
  await db.query('insert into auth.users values($1)', [user]);
  await db.query("insert into finance_holdings values($1,$2,'ABC','Example',10,100,100,'PLN',now())", [id,user]);
  await db.exec(await readFile('supabase/migrations/20261112183000_finance_holding_events.sql','utf8'));
  await db.exec(await readFile('supabase/migrations/20261112183500_finance_holding_event_costs.sql','utf8'));
  await db.query("select set_config('test.user',$1,false)", [user]);
  await db.query("insert into finance_accounts values('bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb',$1,1000,null,'broker_cash')",[user]);
  await db.exec('set role authenticated');
  assert.equal((await db.query('select kind from finance_holding_events')).rows[0].kind,'opening');
  await db.query('select record_finance_holding_purchase($1,2,150,null)', [id]);
  const purchase=(await db.query("select * from finance_holding_events where kind='purchase'")).rows[0];
  assert.equal(Number(purchase.quantity_after),12);
  assert.equal(Number(purchase.amount_pln),300);
  await assert.rejects(db.query('select record_finance_holding_purchase($1,-1,150,null)',[id]),/Invalid purchase/);
  await db.query("select record_finance_holding_purchase($1,1,150,'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb')",[id]);
  assert.equal(Number((await db.query('select balance from finance_accounts')).rows[0].balance),850);
  const countBefore=(await db.query('select count(*)::int n from finance_holding_events')).rows[0].n;
  await assert.rejects(db.query("select record_finance_holding_purchase($1,100,150,'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb')",[id]),/insufficient balance/);
  assert.equal((await db.query('select count(*)::int n from finance_holding_events')).rows[0].n,countBefore);
  await db.query('update finance_holdings set name=name where id=$1',[id]);
  assert.equal((await db.query('select count(*)::int n from finance_holding_events')).rows[0].n,countBefore);
  await db.query('update finance_holdings set quantity=11 where id=$1',[id]);
  assert.equal((await db.query("select count(*)::int n from finance_holding_events where kind='adjustment'")).rows[0].n,1);
  await db.query("update finance_holdings set avg_cost_currency='USD',avg_cost_original=200 where id=$1",[id]);
  const costEvent=(await db.query("select * from finance_holding_events where cost_currency_after='USD'")).rows[0];
  assert.equal(costEvent.cost_currency_before,'PLN');
  assert.equal(Number(costEvent.avg_cost_original_after),200);
  assert.ok(Number(costEvent.avg_cost_original_before)>0);
  await db.query('delete from finance_holdings where id=$1',[id]);
  assert.equal((await db.query("select count(*)::int n from finance_holding_events where kind='removed'")).rows[0].n,1);
  await assert.rejects(db.exec('delete from finance_holding_events'),/permission denied/);
  await db.exec("select set_config('test.user','22222222-2222-4222-8222-222222222222',false)");
  assert.equal((await db.query('select count(*)::int n from finance_holding_events')).rows[0].n,0);
  console.log('Ledger SQL: opening, atomic purchase, adjustment, removal, immutable owner history PASS');
} finally { await db.close(); }
